-- Tabla para Redes Sociales
CREATE TABLE CTR_REDES_SOCIALES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_DOMINIO NUMBER NOT NULL,
    ID_UNIDAD NUMBER NOT NULL,
    URL VARCHAR2(500) NOT NULL,
    NOMBRE_CUENTA VARCHAR2(100) NOT NULL,
    VIGENTE VARCHAR2(2) DEFAULT 'SI' NOT NULL,
    FECHA_CREACION DATE DEFAULT SYSDATE NOT NULL,
    USUARIO_CREACION VARCHAR2(50),
    FECHA_MODIFICACION DATE,
    USUARIO_MODIFICACION VARCHAR2(50)
);

-- Índices
CREATE INDEX IDX_CTR_REDES_SOCIALES_DOMINIO ON CTR_REDES_SOCIALES (ID_DOMINIO);
CREATE INDEX IDX_CTR_REDES_SOCIALES_UNIDAD ON CTR_REDES_SOCIALES (ID_UNIDAD);
CREATE INDEX IDX_CTR_REDES_SOCIALES_VIGENTE ON CTR_REDES_SOCIALES (VIGENTE);

-- Procedimiento para obtener todas las redes sociales
CREATE OR REPLACE PROCEDURE PK_ADMINISTRACION.P_GET_ALL_REDES_SOCIALES(P_CURSOR OUT SYS_REFCURSOR) AS
BEGIN
    OPEN P_CURSOR FOR
    SELECT rs.ID,
           rs.ID_DOMINIO,
           d.DESCRIPCION AS NOMBRE_RED,
           rs.ID_UNIDAD,
           u.DESCRIPCION_DEPENDENCIA AS NOMBRE_UNIDAD,
           rs.URL,
           rs.NOMBRE_CUENTA,
           rs.VIGENTE,
           rs.FECHA_CREACION,
           rs.USUARIO_CREACION
    FROM CTR_REDES_SOCIALES rs
    JOIN CTR_DOMINIOS d ON rs.ID_DOMINIO = d.ID
    JOIN VM_CTR_UNIDADES_DEPENDENCIA u ON rs.ID_UNIDAD = u.CONSECUTIVO
    WHERE rs.VIGENTE = 'SI'
    ORDER BY rs.FECHA_CREACION DESC;
END P_GET_ALL_REDES_SOCIALES;

-- Procedimiento para crear una red social
CREATE OR REPLACE PROCEDURE PK_ADMINISTRACION.P_CREATE_RED_SOCIAL(
    P_ID_DOMINIO IN NUMBER,
    P_ID_UNIDAD IN NUMBER,
    P_URL IN VARCHAR2,
    P_NOMBRE_CUENTA IN VARCHAR2,
    P_USUARIO IN VARCHAR2
) AS
BEGIN
    INSERT INTO CTR_REDES_SOCIALES (
        ID_DOMINIO, ID_UNIDAD, URL, NOMBRE_CUENTA, USUARIO_CREACION
    ) VALUES (
        P_ID_DOMINIO, P_ID_UNIDAD, P_URL, P_NOMBRE_CUENTA, P_USUARIO
    );
END P_CREATE_RED_SOCIAL;

-- Procedimiento para actualizar una red social
CREATE OR REPLACE PROCEDURE PK_ADMINISTRACION.P_UPDATE_RED_SOCIAL(
    P_ID IN NUMBER,
    P_ID_DOMINIO IN NUMBER,
    P_ID_UNIDAD IN NUMBER,
    P_URL IN VARCHAR2,
    P_NOMBRE_CUENTA IN VARCHAR2,
    P_USUARIO IN VARCHAR2
) AS
BEGIN
    UPDATE CTR_REDES_SOCIALES
    SET ID_DOMINIO = P_ID_DOMINIO,
        ID_UNIDAD = P_ID_UNIDAD,
        URL = P_URL,
        NOMBRE_CUENTA = P_NOMBRE_CUENTA,
        FECHA_MODIFICACION = SYSDATE,
        USUARIO_MODIFICACION = P_USUARIO
    WHERE ID = P_ID;
END P_UPDATE_RED_SOCIAL;

-- Procedimiento para eliminar (desactivar) una red social
CREATE OR REPLACE PROCEDURE PK_ADMINISTRACION.P_DELETE_RED_SOCIAL(
    P_ID IN NUMBER,
    P_USUARIO IN VARCHAR2
) AS
BEGIN
    UPDATE CTR_REDES_SOCIALES
    SET VIGENTE = 'NO',
        FECHA_MODIFICACION = SYSDATE,
        USUARIO_MODIFICACION = P_USUARIO
    WHERE ID = P_ID;
END P_DELETE_RED_SOCIAL;

-- Procedimiento para obtener una red social por ID
CREATE OR REPLACE PROCEDURE PK_ADMINISTRACION.P_GET_RED_SOCIAL_BY_ID(
    P_ID IN NUMBER,
    P_CURSOR OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN P_CURSOR FOR
    SELECT rs.ID,
           rs.ID_DOMINIO,
           d.DESCRIPCION AS NOMBRE_RED,
           rs.ID_UNIDAD,
           u.DESCRIPCION_DEPENDENCIA AS NOMBRE_UNIDAD,
           rs.URL,
           rs.NOMBRE_CUENTA,
           rs.VIGENTE
    FROM CTR_REDES_SOCIALES rs
    JOIN CTR_DOMINIOS d ON rs.ID_DOMINIO = d.ID
    JOIN VM_CTR_UNIDADES_DEPENDENCIA u ON rs.ID_UNIDAD = u.CONSECUTIVO
    WHERE rs.ID = P_ID;
END P_GET_RED_SOCIAL_BY_ID;