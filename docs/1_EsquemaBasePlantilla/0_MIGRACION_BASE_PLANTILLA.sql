-- Rol Desarrollador (ID 1) y Administrador (ID 2)
BEGIN
   INSERT INTO CTR_ROLES (ID_ROL, CODIGO_ROL, NOMBRE_ROL, DESCRIPCION, ESTADO, USUARIO_CREACION, MAQUINA_CREACION)
   SELECT 1, 'DESARROLLADOR', 'Desarrollador', 'Rol con acceso total de desarrollo y plantilla', 1, 'SETUP', 'LOCAL' FROM DUAL
   WHERE NOT EXISTS (SELECT 1 FROM CTR_ROLES WHERE ID_ROL = 1 OR CODIGO_ROL = 'DESARROLLADOR');

   INSERT INTO CTR_ROLES (ID_ROL, CODIGO_ROL, NOMBRE_ROL, DESCRIPCION, ESTADO, USUARIO_CREACION, MAQUINA_CREACION)
   SELECT 2, 'ADMINISTRADOR', 'Administrador', 'Rol administrador del sistema', 1, 'SETUP', 'LOCAL' FROM DUAL
   WHERE NOT EXISTS (SELECT 1 FROM CTR_ROLES WHERE ID_ROL = 2 OR CODIGO_ROL = 'ADMINISTRADOR');
